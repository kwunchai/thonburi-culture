            $community = $communities->where('name', $item['community'])->first();

            $culturalItem = CulturalItem::create([
                'title' => $item['title'],
                'description' => $item['content'], // แก้ไขจาก 'content' เป็น 'description'
                'category_id' => $category ? $category->id : $categories->first()->id,
                'community_id' => $community ? $community->id : $communities->first()->id,
