                'content' => 'ชุมชนคลองสานมีภูมิปัญญาการทำเครื่องปั้นดินเผาที่สืบทอดกันมา สามารถปั้นเป็นภาชนะใช้ในครัวเรือน เช่น หม้อดิน กระถางต้นไม้ รูปปั้นตกแต่ง มีเทคนิคเฉพาะในการปั้นและเผา',
